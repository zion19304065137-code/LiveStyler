import {createCanvas} from '@napi-rs/canvas';
import fs from 'node:fs';
// Authored graphics for the editable template library. No text is baked into these plates.
const themes=[['#0b1935','#2768f5','#6ce6ff'],['#101c39','#b28b47','#f1d6a2'],['#f3f8ff','#235ff5','#4dc6dc'],['#fff8ed','#987058','#e3bc8c']];
const result={};fs.mkdirSync('public/template-art',{recursive:true});
function rounded(ctx,x,y,w,h,r){ctx.beginPath();ctx.roundRect(x,y,w,h,r);}
for(let scene=0;scene<4;scene++){
 const [ink,accent,light]=themes[scene];
 for(const [kind,w,h] of [['header',1000,160],['name',820,190],['footer',1600,64],['badge',160,60],['ppt',1280,720]]){
  const c=createCanvas(w,h),x=c.getContext('2d');
  if(kind==='ppt'){
   x.strokeStyle=accent+'bb';x.lineWidth=3;rounded(x,3,3,w-6,h-6,12);x.stroke();x.strokeStyle=light;x.lineWidth=7;
   for(const [px,py,dx,dy] of [[4,4,1,1],[w-4,4,-1,1],[4,h-4,1,-1],[w-4,h-4,-1,-1]]){x.beginPath();x.moveTo(px+dx*38,py);x.lineTo(px,py);x.lineTo(px,py+dy*38);x.stroke();}
  }else{
   const g=x.createLinearGradient(0,0,w,h);g.addColorStop(0,kind==='badge'?accent:ink);g.addColorStop(1,scene<2?'#101624ee':scene===2?'#ffffffee':'#f6ede0ee');
   rounded(x,1,1,w-2,h-2,kind==='badge'?h/2:scene===0?6:18);x.fillStyle=g;x.fill();x.lineWidth=2;x.strokeStyle=light+'88';x.stroke();
   if(kind!=='badge'){
    x.fillStyle=accent;rounded(x,0,14,5,h-28,2);x.fill();
    const bloom=x.createRadialGradient(w*.84,0,0,w*.84,0,w*.5);bloom.addColorStop(0,light+(scene<2?'28':'20'));bloom.addColorStop(1,light+'00');x.fillStyle=bloom;x.fillRect(0,0,w,h);
    x.strokeStyle=light+'55';x.lineWidth=2;x.beginPath();
    if(scene===0){x.moveTo(w*.74,1);x.lineTo(w*.79,18);x.lineTo(w-22,18);x.lineTo(w-4,36);}
    else if(scene===1){x.ellipse(w*.88,h*.12,w*.18,h*.85,-.25,0,Math.PI*2);}
    else if(scene===2){x.moveTo(w-80,18);x.lineTo(w-24,18);x.lineTo(w-24,h-18);}
    else{x.ellipse(w*.94,h*.6,w*.12,h*.8,-.4,0,Math.PI*2);}
    x.stroke();
   }
  }
  const key=`${scene}-${kind}`,bytes=c.toBuffer('image/png');fs.writeFileSync(`public/template-art/${key}.png`,bytes);result[key]='data:image/png;base64,'+bytes.toString('base64');
 }
 for(const portrait of [false,true]){
  const w=portrait?1080:1920,h=portrait?1920:1080,c=createCanvas(w,h),x=c.getContext('2d');
  const g=x.createLinearGradient(0,0,w,h);g.addColorStop(0,scene<2?ink:scene===2?'#eef5ff':'#fff9ef');g.addColorStop(1,scene<2?'#070d1d':scene===2?'#dce9fd':'#e7d3b9');x.fillStyle=g;x.fillRect(0,0,w,h);
  const glow=x.createRadialGradient(w*.83,h*.38,0,w*.83,h*.38,w*.7);glow.addColorStop(0,accent+(scene<2?'50':'22'));glow.addColorStop(1,accent+'00');x.fillStyle=glow;x.fillRect(0,0,w,h);
  x.lineWidth=2;x.strokeStyle=light+(scene<2?'45':'88');
  for(let j=0;j<4;j++){x.beginPath();if(scene===1||scene===3)x.ellipse(w*.97,h*.64,w*(.27+j*.04),h*.54,-.28,0,Math.PI*2);else{x.moveTo(w*(.67+j*.06),h*.2);x.lineTo(w*(.83+j*.06),h*.53);x.lineTo(w*(.58+j*.06),h*.9);}x.stroke();}
  x.fillStyle=accent;x.fillRect(w*.075,h*.1,72,5);x.globalAlpha=.25;x.fillRect(w*.075,h*.9,w*.85,1);x.globalAlpha=1;
  const key=`${scene}-warmup-${portrait?'portrait':'landscape'}`,bytes=c.toBuffer('image/png');fs.writeFileSync(`public/template-art/${key}.png`,bytes);result[key]='data:image/png;base64,'+bytes.toString('base64');
 }
}
fs.writeFileSync('lib/template-art.ts','// Generated by scripts/build-template-art.mjs\nexport const templateArt:Record<string,string>='+JSON.stringify(result)+';\n');
console.log('Built 28 template graphics with editable text kept separate.');
